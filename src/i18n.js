function who(name) {
  if (name === 'Ty') return 'You';
  if (name === 'Komputer') return 'Computer';
  if (name === 'Gracz 1') return 'Player 1';
  if (name === 'Gracz 2') return 'Player 2';
  return name;
}

function bucket(label) {
  return {
    wielokolor: 'multicolor',
    bezbarwne: 'colorless',
    lądy: 'lands',
  }[label] || label;
}

export function t(text) {
  if (text == null) return '';
  const source = String(text);
  if (lang !== 'en') return source;
  if (Object.prototype.hasOwnProperty.call(EXACT, source)) return EXACT[source];
  for (const [pattern, format] of PATTERNS) {
    const match = source.match(pattern);
    if (match) return format(...match.slice(1));
  }
  return source;
}
