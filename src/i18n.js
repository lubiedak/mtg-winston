/**
 * Przełącznik języka interfejsu. Silnik zostawia polskie zdania w stanie gry,
 * a widok tłumaczy je przy rysowaniu. Tekst kart jest osobno, z wydań polskich.
 */
let lang = 'pl';

try {
  const stored = globalThis.localStorage?.getItem('mtg-lang');
  if (stored === 'en' || stored === 'pl') lang = stored;
} catch {
  /* brak localStorage poza przeglądarką */
}

export function getLang() {
  return lang;
}

export function setLang(next) {
  lang = next === 'en' ? 'en' : 'pl';
  try {
    globalThis.localStorage?.setItem('mtg-lang', lang);
  } catch {
    /* podgląd bez zapisu */
  }
  return lang;
}

